<?php
declare(strict_types=1);

/**
 * AaZa HRMS - CLI Demo Data Tool
 * 
 * Usage:
 *   php tools/seed_demo.php --company=1 --password=MySecureDemoPassword123
 *   php tools/seed_demo.php --company=1                 # Auto-generates secure password
 *   php tools/seed_demo.php --company=1 --remove        # Removes demo data safely
 *   php tools/seed_demo.php --help
 */

require_once dirname(__DIR__) . '/includes/bootstrap.php';
require_once dirname(__DIR__) . '/includes/demo_seed.php';

if (php_sapi_name() !== 'cli') {
    echo "This tool must be run from the command line.\n";
    exit(1);
}

$longOpts = [
    'company:',
    'password::',
    'remove',
    'help',
];

$options = getopt('', $longOpts);

if (isset($options['help'])) {
    echo "\nAaZa HRMS - Demo Data Seeder & Cleaner (CLI)\n";
    echo "=============================================\n";
    echo "Usage:\n";
    echo "  php tools/seed_demo.php --company=<ID> [--password=<PASS>]\n";
    echo "  php tools/seed_demo.php --company=<ID> --remove\n\n";
    echo "Options:\n";
    echo "  --company=<ID>       Target company ID (required)\n";
    echo "  --password=<PASS>    Password for demo users (optional; auto-generated if omitted)\n";
    echo "  --remove             Remove seeded demo data for the specified company\n";
    echo "  --help               Display this help message\n\n";
    exit(0);
}

$companyId = isset($options['company']) ? (int)$options['company'] : 0;
if ($companyId <= 0) {
    // List available companies to assist the operator
    $pdo = db();
    $companies = $pdo->query("SELECT id, name, code FROM companies ORDER BY id ASC")->fetchAll();
    echo "\nError: Missing or invalid --company parameter.\n";
    echo "Available companies:\n";
    foreach ($companies as $c) {
        echo sprintf("  [%d] %s (%s)\n", $c['id'], $c['name'], $c['code']);
    }
    echo "\nExample: php tools/seed_demo.php --company=1\n\n";
    exit(1);
}

$pdo = db();
$stComp = $pdo->prepare("SELECT id, name, code FROM companies WHERE id = ?");
$stComp->execute([$companyId]);
$company = $stComp->fetch();

if (!$company) {
    echo "\nError: Company ID {$companyId} not found in database.\n\n";
    exit(1);
}

// -------------------------------------------------------------
// Removal Mode
// -------------------------------------------------------------
if (isset($options['remove'])) {
    echo "\nRemoving demo data for company: {$company['name']} ({$company['code']})...\n";
    try {
        $removed = demo_unseed($pdo, $companyId);
        echo "============================================================\n";
        echo " Demo Data Cleanup Completed Successfully\n";
        echo "============================================================\n";
        foreach ($removed as $k => $count) {
            echo sprintf("  %-25s : %d removed\n", ucwords(str_replace('_', ' ', $k)), $count);
        }
        echo "============================================================\n";
        echo "Genuine company data, production employees, and admins remain untouched.\n\n";
        exit(0);
    } catch (Throwable $e) {
        echo "\n[ERROR] Demo cleanup failed: " . $e->getMessage() . "\n\n";
        exit(1);
    }
}

// -------------------------------------------------------------
// Seeding Mode
// -------------------------------------------------------------
$password = $options['password'] ?? null;
$autoGenerated = false;

if (empty($password) || !is_string($password)) {
    // Generate secure 14-char password
    $password = 'Demo#' . bin2hex(random_bytes(3)) . '!9A';
    $autoGenerated = true;
}

echo "\nSeeding fake demo data for company: {$company['name']} ({$company['code']})...\n";

try {
    $counts = demo_seed($pdo, $companyId, $password);
    echo "============================================================\n";
    echo " Demo Data Seeded Successfully!\n";
    echo "============================================================\n";
    echo " Target Company: {$company['name']} [{$company['code']}]\n";
    echo "------------------------------------------------------------\n";
    foreach ($counts as $k => $count) {
        echo sprintf("  %-22s : %d created\n", ucwords(str_replace('_', ' ', $k)), $count);
    }
    echo "------------------------------------------------------------\n";
    echo " Demo User Accounts Created / Configured:\n";
    echo "  1) demo_hr        (Role: HR Manager)          -> demo_hr@example.com\n";
    echo "  2) demo_manager   (Role: Department Manager)  -> demo_manager@example.com\n";
    echo "  3) demo_employee  (Role: Staff Employee)      -> demo_employee@example.com\n";
    echo "------------------------------------------------------------\n";
    echo " Demo Password: {$password}" . ($autoGenerated ? "  (Auto-generated, save now)" : "") . "\n";
    echo "============================================================\n\n";
    exit(0);
} catch (Throwable $e) {
    echo "\n[ERROR] Demo seeding failed: " . $e->getMessage() . "\n\n";
    exit(1);
}

